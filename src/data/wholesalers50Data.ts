/**
 * Generates formatted CSV text from the 50 Wholesalers dataset
 */
export const generate50WholesalersCsvText = (defaultPasswordPrefix = 'Dropthan@2026'): string => {
  const headers = ['Phone', 'Password', 'CompanyName', 'ContactPerson', 'City', 'StoreAddress', 'GSTIN', 'Bio', 'Website', 'Instagram'];
  const rows = WHOLESALERS_50_DATASET.map((w, idx) => {
    const pass = w.password || `${defaultPasswordPrefix.split('@')[0]}@${w.phone.slice(-4)}`;
    return [
      `"${w.phone}"`,
      `"${pass}"`,
      `"${w.companyName}"`,
      `"${w.fullName}"`,
      `"${w.location}"`,
      `"${w.storeAddress.replace(/"/g, '""')}"`,
      `"${w.gstin}"`,
      `"${w.bio.replace(/"/g, '""')}"`,
      `"${w.website}"`,
      `"${w.instagram}"`,
    ].join(',');
  });
  return [headers.join(','), ...rows].join('\n');
};
